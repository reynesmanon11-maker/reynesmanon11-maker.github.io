test('QR : identique à la référence (version, masque, chaque module)', () => {
  for (const r of REFERENCES) {
    const masqueForce = r.texte === 'HELLO WORLD' ? { masque: r.masque } : {};
    const q = qr(r.texte, masqueForce);
    assert.equal(q.version, r.version, r.texte);
    assert.equal(q.masque, r.masque, r.texte);
    assert.deepEqual(lignes(q.modules), r.lignes, r.texte);
  }
});

test('QR : Reed-Solomon sur l’exemple de la norme (version 1-M, « 01234567 »)', () => {
  // ISO/IEC 18004, annexe I : données et 10 octets de correction attendus.
  const donnees = [0x10, 0x20, 0x0c, 0x56, 0x61, 0x80, 0xec, 0x11, 0xec, 0x11, 0xec, 0x11, 0xec, 0x11, 0xec, 0x11];
  assert.deepEqual(correction(donnees, 10), [0xa5, 0x24, 0xd4, 0xc1, 0xed, 0x36, 0xc7, 0x87, 0x2c, 0x55]);
});

test('QR : la version grandit avec le texte, et un texte trop long est refusé', () => {
  assert.equal(qr('x'.repeat(14)).version, 1);
  assert.equal(qr('x'.repeat(15)).version, 2);
  assert.equal(qr('x'.repeat(213)).version, 10);
  assert.throws(() => qr('x'.repeat(214)), /trop long/);
});

test('QR : le SVG garde la marge blanche et échappe le titre', () => {
  const s = qrSvg('https://exemple.fr/?a=1&b=<2>', { titre: 'Ouvrir « a & b »' });
  const { taille } = qr('https://exemple.fr/?a=1&b=<2>');
  assert.match(s, new RegExp(`viewBox="0 0 ${taille + 8} ${taille + 8}"`));
  assert.match(s, /aria-label="Ouvrir « a &amp; b »"/);
  assert.doesNotMatch(s, /<2>/);
});
